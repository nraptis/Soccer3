#!/usr/bin/env python3
"""Enumerate BitPlaneTool's complete bank; --check verifies the checked-in data."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Dead Code/BitPlaneToolPlans.inc"
PAIR_MASKS = sorted(
    (1 << first) | (1 << second)
    for first in range(8)
    for second in range(first + 1, 8)
    if 2 <= second - first <= 6
)


def enumerate_plans():
    """Fill cells with pairs, enforcing row/column disjointness as we go.

    Sort only the first row's masks. Every labeled grid has exactly one such
    representative and exactly 4! column permutations. The fourth row is
    forced by the first three; no random choices, repairs or omitted grids.
    """
    plans = []
    cells = [0] * 16
    column_masks = [0] * 4

    def visit(index, row_mask):
        if index == 12:
            last_row = [255 ^ mask for mask in column_masks]
            if any(mask not in PAIR_MASKS for mask in last_row):
                return
            assert sum(bin(mask).count("1") for mask in last_row) == 8
            assert last_row[0] | last_row[1] | last_row[2] | last_row[3] == 255
            plans.append(tuple(cells[:12] + last_row))
            return
        row, column = divmod(index, 4)
        if column == 0:
            row_mask = 0
        for mask in PAIR_MASKS:
            if (mask & row_mask) or (mask & column_masks[column]):
                continue
            if row == 0 and column and mask <= cells[index - 1]:
                continue
            cells[index] = mask
            column_masks[column] |= mask
            visit(index + 1, row_mask | mask)
            column_masks[column] ^= mask

    visit(0, 0)
    assert len(plans) == len(set(plans)) == 8808
    return sorted(plans)


def render(plans):
    # Twelve 5-bit pair indices fit in 60 bits. The last row is derived.
    indices = {mask: index for index, mask in enumerate(PAIR_MASKS)}
    words = [sum(indices[mask] << (5 * cell) for cell, mask in enumerate(plan[:12]))
             for plan in plans]
    assert len(set(words)) == len(words)
    lines = [
        "// Generated by Tools/generate_bit_plane_tool.py. Do not edit by hand.",
        "// 8,808 grids with ascending first-row masks; 12 five-bit pair IDs per word.",
        "// Pair IDs index BitPlaneTool::kPairMasks. Last row is each column's complement.",
    ]
    for start in range(0, len(words), 4):
        lines.append("    " + " ".join(f"0x{word:016X}ULL," for word in words[start:start + 4]))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    plans = enumerate_plans()
    text = render(plans)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("BitPlaneToolPlans.inc is out of date; run this script without --check")
    else:
        OUTPUT.write_text(text)
    print(f"{'Verified' if args.check else 'Generated'} {len(plans):,} base plans x 24 column orders "
          f"= {len(plans) * 24:,} grids; packed bank {len(plans) * 8:,} bytes.")


if __name__ == "__main__":
    main()
